import type { Page } from 'playwright';
import { historyDetail, historyPage, type HistoryCard, type HistoryOrder, type HistoryQuery, type OrderHistory } from './order-history.js';

const isHistory = (url: string) => new URL(url).pathname === '/v1/layout/order_history';

async function openHistory(page: Page) {
  const [response] = await Promise.all([
    page.waitForResponse(r => isHistory(r.url()), { timeout: 20000 }),
    page.goto('https://blinkit.com/account/orders', { waitUntil: 'domcontentloaded', timeout: 30000 }),
  ]);
  if (!response.ok()) throw new Error('Blinkit order history unavailable. Check login and retry.');
  return historyPage(await response.json());
}

export async function readBlinkitOrder(page: Page, card: HistoryCard): Promise<HistoryOrder> {
  const [response] = await Promise.all([
    page.waitForResponse(r => new URL(r.url()).pathname === `/v1/layout/order_details/${card.id}`, { timeout: 20000 }),
    page.goto(card.url, { waitUntil: 'domcontentloaded', timeout: 30000 }),
  ]);
  if (!response.ok()) throw new Error('Blinkit order detail unavailable. Check login and retry.');
  const responseDate = new Date(response.headers()['date'] ?? '');
  return historyDetail(await response.json(), card, Number.isFinite(responseDate.getTime()) ? responseDate : new Date());
}

export async function latestBlinkitOrder(page: Page): Promise<string | null> {
  const { cards } = await openHistory(page);
  return cards.length ? JSON.stringify(await readBlinkitOrder(page, cards[0]), null, 2) : null;
}

/** Consume responses generated by normal account-page navigation/scrolling.
 * No credentials are copied, private endpoints fetched directly, or account/cart controls clicked. */
export async function blinkitOrderHistory(page: Page, query: HistoryQuery): Promise<OrderHistory> {
  const result: OrderHistory = { platform: 'blinkit', startDate: query.startDate, endDate: query.endDate,
    currency: 'INR', orders: [], complete: false, warnings: [] };
  let batch = await openHistory(page);
  const detailPage = await page.context().newPage();
  const seen = new Set<string>();
  let previousDate = '9999-12-31';
  let ordered = true;
  try {
    for (let pageIndex = 0; pageIndex < 50; pageIndex++) {
      let added = 0;
      for (const card of batch.cards) {
        if (seen.has(card.id)) continue;
        if (seen.size >= query.maxOrders) {
          result.warnings.push('Inspection limit reached; narrow the date range or increase max_orders.');
          return result;
        }
        seen.add(card.id); added++;
        let order: HistoryOrder;
        try { order = await readBlinkitOrder(detailPage, card); }
        catch {
          result.warnings.push(`Could not read or reconcile order ${card.id}; results are incomplete.`);
          // Its date is unknown: never declare this range complete later.
          continue;
        }
        if (order.date > previousDate) ordered = false;
        previousDate = order.date;
        if (order.date >= query.startDate && order.date <= query.endDate) result.orders.push(order);
        if (ordered && order.date < query.startDate) {
          result.complete = result.warnings.length === 0;
          return result; // newest-first history has crossed the inclusive lower boundary
        }
      }
      if (!batch.hasMore) {
        result.complete = result.warnings.length === 0;
        return result;
      }
      if (!added || seen.size >= query.maxOrders) {
        result.warnings.push(!added ? 'History pagination repeated orders without progress.' : 'Inspection limit reached; narrow the date range or increase max_orders.');
        return result;
      }
      // Scroll the actual history page to request its next batch, including nested scroll roots.
      const nextResponse = page.waitForResponse(r => isHistory(r.url()), { timeout: 10000 }).catch(() => null);
      await page.evaluate(() => {
        for (const el of [document.scrollingElement, ...document.querySelectorAll('.list, .page-layout')]) {
          if (el) el.scrollTop = el.scrollHeight;
        }
        window.scrollTo(0, document.body.scrollHeight);
      });
      const response = await nextResponse;
      if (!response?.ok()) {
        result.warnings.push('Blinkit did not load the next history page; results are incomplete.');
        return result;
      }
      try { batch = historyPage(await response.json()); }
      catch {
        result.warnings.push('Blinkit returned an unrecognized history page; results are incomplete.');
        return result;
      }
    }
    result.warnings.push('History page limit reached; narrow the date range.');
    return result;
  } finally { await detailPage.close(); }
}
